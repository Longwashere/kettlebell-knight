import type { SecretTrialId } from '../../shared/secretTrials';

/**
 * The words and colours of each secret stage (src/shared/secretTrials.ts): the call on the expedition victory
 * card, then the trial screen (SecretTrial.tsx). Numbers come from the spec, so `{reps}` / `{seconds}` are filled in.
 */
export interface SecretTrialCopy {
  /** Victory-card call to the trial. */
  callTitle: string;
  callLine: string;
  callButton: string;
  /** Trial screen. */
  title: string;
  /** Intro before the clock starts: lead-in, the weapon's name (highlighted), then the condition. */
  introLead: string;
  introAfter: string;
  goalLine: string;
  warning: string;
  startLine: string;
  repLabel: string;
  formHint: string;
  wrongMove: string;
  /** A rep below the power bar (power trials) / off the beat (rhythm trials). */
  weakRep?: string;
  offBeat?: string;
  clockLabel: string;
  clockCaption: string;
  wonTitle: string;
  wonLine: string;
  lostIcon: string;
  lostTitle: string;
  lostLine: string;
  weaponName: string;
  /** The blacksmith's tag on the weapon until it is won. */
  sealed: string;
  /** Accent (titles, rep count) and the bar gradient [from, to]. */
  accent: string;
  bar: [string, string];
  /** Clock accent. */
  clock: string;
}

