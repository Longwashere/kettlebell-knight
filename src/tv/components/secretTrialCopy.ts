/** Fills `{reps}`, `{seconds}` and `{done}` into a copy line. */
export const fillCopy = (line: string, v: { reps?: number; seconds?: number; done?: number }) =>
  line.replace('{reps}', `${v.reps ?? ''}`).replace('{seconds}', `${v.seconds ?? ''}`).replace('{done}', `${v.done ?? ''}`);
